/* ---- v0.8.0（2026-10-28）接收通道提速 + 老通路清仓 =====================
 *   现场（v0.7.8，17:51:54~17:52:00）：桥接侧连收 6 条完整 `+MSUB`，
 *   MCU 侧只有 `urc b=270 l=11 m=0` —— 收到 11 行、没一行的头是 +MSUB，
 *   于是版本消息永远没被解析，永不升级。
 *
 *   定案：**不是解析错，是整字节丢在接收寄存器的覆盖里。**
 *   UART3 只有一个接收寄存器，115200 下一字节 87 us；旧主循环一圈
 *   = data_poll + at_pump + mqtt_poll + 32 位 at_ms 比较 ≈ 50~90 us，
 *   刚好压在 87 us 上 ⇒ 每圈慢一次吃一个字节。62 字节的 URC 丢 20 来个，
 *   行头那 5 个字符最先没 ⇒ 与"m=0 但 l 正常"完全吻合。
 *   （v0.7.6 的 m=3/6 是同一个病，只是运气好。）
 *
 *   本版三处改动：
 *     ① 主循环按 1:8 抽稀（app_main.c）：7 圈只收字节（≈20 us），
 *        第 8 圈才喂狗 / mqtt_poll / 判 500 ms。最坏空档 60 us < 87 us。
 *     ② at_pump 无在途字节直接返回（省掉每圈两次 xdata 访问），
 *        并把**每一条够长的行**都留档到 g_urc（不再只留 +MSUB），
 *        心跳日志加一行 `urc [%s]` —— 下次一眼看到线上原文。
 *     ③ 删掉 6 条全工程 0 调用点的老通路（at_poll / URC 注册表 /
 *        at_binary_enter,read,exit / at_lock,unlock,is_locked），
 *        腾出约 550 B 代码 + 342 B xdata 给①②用。
 *
 *   ★ 本版没有改任何网络侧命令序列、没有改分区、没有改 BL。
 *   ★ 板上要跑本版（0.8.0），直链上挂 0.8.1 的镜像才能验证升级。
 *---------------------------------------------------------------------------*/

