/*==============================================================================
 *  uart2_data.h  --  串口2 数据口：32 位定长帧的接收与解析
 *  Project : Project/APP/STC32G_OTA.uvproj    CODE = 0xFF4000
 *  Platform: STC32G12K128 (Keil C251, Huge)
 *
 *  ── 为什么是串口2 ──────────────────────────────────────────────────────
 *   本板的三个串口已经分好工，谁也不许抢：
 *       UART1  P3.0/P3.1  日志（同时也被 STC-ISP 占用，不能接别的东西）
 *       UART3  P0.0/P0.1  AT 通道 → Air724 模组
 *       UART2  P1.0/P1.1  ★ 就是本模块：外部数据源
 *
 *  ── ★ 一个必须知道的硬约束：串口2 与 AT 通道**同波特率** ──────────────
 *   STC32G 的 UART2 没有"波特率源选择"位，它固定吃 **Timer2**；UART3 在
 *   S3ST3=0（本工程正是这么配的）时也吃 Timer2。一个定时器只有一个重装值
 *   ⇒ 两边必然同速。AT 通道实测且固定为 **115200**，所以串口2 也是 115200。
 *   要换成 9600 的外部设备，只有两条路：把数据口挪到 UART4（Timer4），
 *   或者把 AT 通道一起降速（实测这条模组不认 AT+IPR，走不通）。
 *
 *  ── ★ 第二个硬约束：只能轮询，收不到中断 ─────────────────────────────
 *   APP 侧 EA=0（向量表在 BL，APP 的同名 ISR 永远不会被执行，见 app_main.c
 *   顶部那段）。所以本模块是**纯轮询**：主循环每圈调一次 data_poll()，
 *   一次把在途字节全部读走。115200 下一字节 87 us，主循环一圈几 us，
 *   余量足够；但**任何阻塞超过 1 ms 的操作都会丢字节**（AT 命令、日志打印）。
 *   丢掉的字节由"帧头 + CRC"兜住：坏帧直接丢，绝不污染数据。
 *
 *  ── 帧格式（9 字节定长，大端）──────────────────────────────────────────
 *      偏移  长度  含义
 *       0     1    0xAA      帧头 1
 *       1     1    0x55      帧头 2
 *       2     1    模板序号  1..10（对应上报模板 D1..D10）
 *       3     4    数据      u32 大端
 *       7     2    CRC16     CRC-16/CCITT-FALSE（init 0xFFFF, poly 0x1021）
 *                            覆盖偏移 0..6 共 7 字节，大端存放
 *   CRC 覆盖帧头是有意的：帧头抄错也必须算坏帧，否则"AA 55"一旦错位，
 *   后面的字节会被当成合法数据写进模板，现场极难发现。
 *============================================================================*/
#ifndef __UART2_DATA_H
#define __UART2_DATA_H

#include "ota_mcu.h"

/* 上报模板个数（D1..D10）。改这里要同步改 docs/APP_MQTT.md 的 payload 说明。 */
#define DATA_SLOT_N         10U

/* 没有数据的槽位在 MQTT payload 里打这个（用户的约定值） */
#define DATA_DEF_TXT        "##1229##"

/* 帧长：AA 55 IDX D[4] CRC[2] */
#define DATA_FRAME_LEN      9U

/*------------------------------------------------------------------------------
 * 初始化：配 P1.0(RXD2)/P1.1(TXD2) + S2CON 模式1，**不动 Timer2**
 *   ★ 必须在 at_uart_init() 之后调用：那一步才把 Timer2 跑起来并定好 115200。
 *     本函数只开 UART2 自己的接收使能，不碰波特率源。
 *------------------------------------------------------------------------------*/
void data_init(void);

/*------------------------------------------------------------------------------
 * 轮询：把在途字节读完并喂给帧状态机。**绝不等待**，无字节立即返回。
 *   调用频率决定丢不丢字节 —— 主循环每圈一次是设计前提。
 *------------------------------------------------------------------------------*/
void data_poll(void);

/* 槽位查询（零指针：序号进、值出，不传任何地址） */
u8   data_have(u8 idx);        /* idx = 1..10；1 = 这个槽位收到过有效帧 */
u32  data_value(u8 idx);       /* idx = 1..10；无效时返回 0（配合 data_have 用） */
u16  data_mask(void);          /* bit0..bit9 对应 D1..D10 */

/* 统计（心跳里打出来，用来区分"没接设备"和"线接错/波特率错"） */
u16  data_bytes(void);         /* 累计收到的字节数            */
u16  data_frames(void);        /* 合格帧数                    */
u16  data_bad_crc(void);       /* 帧头对、CRC 错的帧数        */
u16  data_bad_seq(void);       /* 帧头对、序号越界的帧数      */

#endif /* __UART2_DATA_H */
